/**
 * The share card, written as pixels.
 *
 * X, Slack, Facebook and LinkedIn all refuse an SVG for a link preview, so the
 * card has to exist as a raster as well. Every rasteriser worth using is a
 * dependency or a browser, and this particular image does not need one: it is a
 * flat field with axis-aligned black squares on it, which is a thing that can
 * be written straight into a PNG.
 *
 * So it reads the same src/assets/untypo-logo.svg the masthead inlines and the
 * favicon is built from, fills the pixels itself, and deflates them with the
 * zlib that ships with node. One source of truth, no toolchain, and the file
 * can be regenerated by anyone who has the repo.
 *
 *   node scripts/make-share-png.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';

const W = 1200;
const H = 630;
const BG = [255, 0, 0];
const FG = [0, 0, 0];
/** How much of the card's width the mark takes. */
const MARK_WIDTH = 800;

const svg = readFileSync(new URL('../src/assets/untypo-logo.svg', import.meta.url), 'utf8');

// Every shape in the mark is an axis-aligned square, as a polygon or a rect.
const squares = [];
for (const m of svg.matchAll(/points="([^"]+)"/g)) {
  const n = m[1].replace(/,/g, ' ').trim().split(/\s+/).map(Number);
  const xs = n.filter((_, i) => i % 2 === 0);
  const ys = n.filter((_, i) => i % 2 === 1);
  squares.push([Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]);
}
for (const m of svg.matchAll(/<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"/g)) {
  const [x, y, w, h] = m.slice(1).map(Number);
  squares.push([x, y, x + w, y + h]);
}
if (!squares.length) throw new Error('no shapes found in the logo');

const bx0 = Math.min(...squares.map((s) => s[0]));
const by0 = Math.min(...squares.map((s) => s[1]));
const bx1 = Math.max(...squares.map((s) => s[2]));
const by1 = Math.max(...squares.map((s) => s[3]));

const scale = MARK_WIDTH / (bx1 - bx0);
const offX = (W - MARK_WIDTH) / 2;
const offY = (H - (by1 - by0) * scale) / 2;

// One filter byte per row, then RGB triples.
const stride = W * 3 + 1;
const raw = Buffer.alloc(stride * H);
for (let y = 0; y < H; y++) {
  const row = y * stride;
  raw[row] = 0;
  for (let x = 0; x < W; x++) {
    const i = row + 1 + x * 3;
    raw[i] = BG[0];
    raw[i + 1] = BG[1];
    raw[i + 2] = BG[2];
  }
}
for (const [sx0, sy0, sx1, sy1] of squares) {
  const x0 = Math.round((sx0 - bx0) * scale + offX);
  const x1 = Math.round((sx1 - bx0) * scale + offX);
  const y0 = Math.round((sy0 - by0) * scale + offY);
  const y1 = Math.round((sy1 - by0) * scale + offY);
  for (let y = Math.max(0, y0); y < Math.min(H, y1); y++) {
    const row = y * stride;
    for (let x = Math.max(0, x0); x < Math.min(W, x1); x++) {
      const i = row + 1 + x * 3;
      raw[i] = FG[0];
      raw[i + 1] = FG[1];
      raw[i + 2] = FG[2];
    }
  }
}

const TABLE = Int32Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c;
});
const crc32 = (buf) => {
  let c = -1;
  for (const b of buf) c = TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ -1) >>> 0;
};
const chunk = (type, data) => {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
};

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(W, 0);
ihdr.writeUInt32BE(H, 4);
ihdr[8] = 8;   // eight bits a channel
ihdr[9] = 2;   // truecolour, no alpha
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0)),
]);

const out = new URL('../public/og.png', import.meta.url);
writeFileSync(out, png);
console.log(`${W}x${H}, ${squares.length} squares, ${png.length} bytes -> public/og.png`);
